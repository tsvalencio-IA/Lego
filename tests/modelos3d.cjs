const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const dir=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(dir,p),"utf8");
const html=read("index.html"),cad=read("modelos3d-engine.js"),ui=read("modelos3d-ui.js"),models=read("modelos3d-catalogo.js");
assert.match(html,/modelos3d-engine\.js\?v=11\.0\.0/);
assert.match(html,/modelos3d-ui\.js\?v=11\.0\.0/);
assert.match(html,/modelos3d-catalogo\.js\?v=9\.0\.0/);
for(const id of ["model3dDetail","model3dCanvas","model3dImport","model3dNext","model3dRotate","model3dClose"])
 assert(html.includes('id="'+id+'"'),"Falta controle "+id);
assert(read("catalogo-app.js").includes("data-view3d"),"Cards não expõem o visualizador 3D");
assert(!html.includes('id="prompt"'),"Invenção livre não pode voltar");
const c={window:{},globalThis:{},module:{exports:{}},console,Date,Map,Set};
c.globalThis=c.window;
vm.runInNewContext(models,c,{filename:"modelos3d-catalogo.js"});
vm.runInNewContext(cad,c,{filename:"modelos3d-engine.js"});
const engine=c.module.exports;
assert.equal(typeof engine.CADViewer,"function");
const frog=read("modelos3d/lego-sapo-10698-packed.mpd"),meta=engine.inspect(frog);
assert(meta.stepSeparators>=10);
assert(meta.partsReferenced>=16);
assert.equal(meta.isMultiPart,true);
assert.equal(c.window.OTTO_MODELOS3D["lego-sapo"].quality,"reconstrucao-preliminar");
assert(c.window.OTTO_MODELOS3D["lego-sapo"].review.includes("conferência"));
assert.throws(()=>engine.inspect("not an LDraw file"));
assert.throws(()=>engine.inspect("1 2 0 0 0 1 0 0 0 1 0 0 0 1 ../../bad.php"));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,"IDs DOM duplicados");
assert(ui.includes("modelo 3D")||ui.includes("Modelo 3D"));
assert(ui.includes("engine.projectSource"),"3D não busca modelo vinculado ao projeto");
console.log("CATÁLOGO 3D v7 PASS: projeto LEGO referenciado, malhas LDraw, navegação e origem explícita.");
